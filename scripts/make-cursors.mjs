function write(name, map, scale = S, outline = OUT, fill = FILL) {
  const rows = map.trim().split("\n");
  const w = Math.max(...rows.map((r) => r.length));
  let rects = "";
  rows.forEach((row, y) =>
    [...row].forEach((ch, x) => {
      if (ch === ".") return;
      rects += `<rect x="${x * scale}" y="${y * scale}" width="${scale}" height="${scale}" fill="${ch === "o" ? outline : fill}"/>`;
    }),
  );
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${w * scale}" height="${rows.length * scale}" viewBox="0 0 ${w * scale} ${rows.length * scale}" shape-rendering="crispEdges">${rects}</svg>`;
  writeFileSync(`public/cursors/${name}.svg`, svg);
}
for (const [name, map] of Object.entries(maps)) write(name, map);
for (const [name, base, scale, outline, fill] of variants) write(name, maps[base], scale, outline, fill);
