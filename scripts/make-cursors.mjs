// Generates the pixel-art cursors in public/cursors from ASCII maps.
// o = outline, w = fill, . = transparent. Scale 2px per pixel.
import { writeFileSync } from "node:fs";

const OUT = "#ff5c9d", FILL = "#ffffff", S = 2;
// [name, map, scale, outline, fill]: big a11y cursors reuse the arrow at 2.5x.
const variants = [
  ["big-black", "arrow", 5, "#ffffff", "#000000"],
  ["big-white", "arrow", 5, "#000000", "#ffffff"],
];
