// Content-hashes every image in media/images into public/images and writes a manifest.
// Replacing a photo therefore always changes its URL, so neither the browser cache nor
// Next's image optimiser can ever serve a stale copy. Runs before `dev` and `build`.
//
//   media/images/portrait.webp          → public/images/portrait.3fa9c1d2.webp
//   media/images/projects/magnil.webp   → public/images/projects/magnil.8be0a1f4.webp
import { createHash } from "node:crypto";
import { mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync, existsSync } from "node:fs";
import { join, relative, dirname, extname, basename } from "node:path";

const SRC = "media/images";
const OUT = "public/images";
const MANIFEST = "src/content/images.generated.ts";
const EXT = new Set([".webp", ".avif", ".jpg", ".jpeg", ".png", ".svg"]);

const walk = (dir) =>
  existsSync(dir)
    ? readdirSync(dir).flatMap((f) => {
        const p = join(dir, f);
        return statSync(p).isDirectory() ? walk(p) : EXT.has(extname(f).toLowerCase()) ? [p] : [];
      })
    : [];

rmSync(OUT, { recursive: true, force: true }); // drop every previous hashed copy
const map = {};
for (const file of walk(SRC).sort()) {
  const rel = relative(SRC, file).split("\\").join("/");
  const hash = createHash("sha256").update(readFileSync(file)).digest("hex").slice(0, 10);
  const ext = extname(rel);
  const outRel = join(dirname(rel), `${basename(rel, ext)}.${hash}${ext}`).split("\\").join("/");
  mkdirSync(join(OUT, dirname(rel)), { recursive: true });
  writeFileSync(join(OUT, outRel), readFileSync(file));
  map[rel] = `/images/${outRel}`;
}

writeFileSync(
  MANIFEST,
  `// Generated by scripts/build-images.mjs — do not edit. Add images to media/images and run \`npm run images\`.
export const imageManifest: Record<string, string> = ${JSON.stringify(map, null, 2)};
`,
);
console.log(`images: ${Object.keys(map).length} hashed → ${OUT}`);
